import { call } from './api.mjs';
import { DatabaseSync } from 'node:sqlite';
const raw = new DatabaseSync(process.env.DB_PATH);
const t = 'r' + Date.now().toString(36);
const ok = (l, c, x = '') => console.log((c ? 'PASS ' : 'FAIL ') + l + (x ? `  [${x}]` : ''));
const s = await call('POST', '/auth/signup', { body: { email: `acc${t}@t.com`, password: 'Test1234!', name: 'Acc', role: 'accountant' } });
const AT = s.data.token;
raw.prepare("UPDATE users SET accountant_tier='firm' WHERE id=?").run(s.data.user.id);
const mk = async (n) => (await call('POST', '/clients/managed', { token: AT, body: { tradeName: 'Biz ' + n, tin: '1' + n, userId: `b${n}${t}`, password: 'Temp1234' } })).data.client.id;
const A = await mk('A'), B = await mk('B');
const st = (await call('POST', '/staff', { token: AT, body: { name: 'ana', username: 'ana' + t, password: 'Staff123' } })).data.staff.id;
await call('PUT', `/staff/${st}/assign`, { token: AT, body: { clientIds: [A] } });
const add = await call('POST', `/staff/${st}/clients`, { token: AT, body: { clientId: B } });
ok('add B keeps A', add.status === 200 && add.data.staff.assignedClientIds.length === 2, String(add.data.staff?.assignedClientIds?.length));
const rem = await call('DELETE', `/staff/${st}/clients/${A}`, { token: AT });
ok('remove A keeps B', rem.status === 200 && rem.data.staff.assignedClientIds.length === 1 && rem.data.staff.assignedClientIds[0] === B);
ok('add rejects a client not yours', (await call('POST', `/staff/${st}/clients`, { token: AT, body: { clientId: 'nope' } })).status === 400);
const other = (await call('POST', '/auth/signup', { body: { email: `x${t}@t.com`, password: 'Test1234!', name: 'X', role: 'accountant' } })).data.token;
ok('other firm cannot touch this staff', (await call('POST', `/staff/${st}/clients`, { token: other, body: { clientId: A } })).status === 404);
